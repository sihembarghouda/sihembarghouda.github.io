// Éléments HTML
const languageButton = document.getElementById("language-toggle");
const navLinks = document.querySelector(".nav-links");

// Langue actuelle
let currentLanguage = "fr";

// Traduction des éléments
function setLanguage(language) {
  if (!translations[language]) return;

  currentLanguage = language;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const translatedText = translations[language][key];

    if (translatedText !== undefined) {
      element.textContent = translatedText;
    }
  });

  // Compatibilité avec les éléments HTML utilisant data-fr / data-en
  document.querySelectorAll("[data-fr][data-en]").forEach((element) => {
    element.textContent = element.dataset[language];
  });

  languageButton.textContent = language === "fr" ? "EN" : "FR";
  languageButton.setAttribute(
    "aria-label",
    language === "fr" ? "Switch to English" : "Passer en français"
  );
}

// Changement de langue
languageButton.addEventListener("click", () => {
  setLanguage(currentLanguage === "fr" ? "en" : "fr");
});

// Fermeture du menu mobile après clic
if (navLinks) {
  navLinks.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      navLinks.classList.remove("open");
    });
  });
}

// Année automatique
const footerYear = document.getElementById("year");

if (footerYear) {
  footerYear.textContent = new Date().getFullYear();
}

// Initialisation
setLanguage("fr");

